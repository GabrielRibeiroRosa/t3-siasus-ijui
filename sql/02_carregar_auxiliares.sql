-- Carga das tabelas auxiliares. A tabela micro vem do DATASUS em cp850; as demais, em latin1.
USE dbsia;

LOAD DATA INFILE 'D:/T3/uploads/micro.csv' INTO TABLE micro CHARACTER SET cp850
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/municipio.csv' INTO TABLE tb_municip CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/rl.csv' INTO TABLE rl CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/cadgerrs.csv' INTO TABLE cadgerrs CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/cbo.csv' INTO TABLE cbo CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/cid10.csv' INTO TABLE cid CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;
LOAD DATA INFILE 'D:/T3/uploads/procedimento.csv' INTO TABLE procedimentos CHARACTER SET latin1
  FIELDS TERMINATED BY ',' ENCLOSED BY '"' LINES TERMINATED BY '\r\n' IGNORE 1 ROWS;
SHOW WARNINGS LIMIT 10;

SELECT 'micro' AS tabela, COUNT(*) AS linhas FROM micro
UNION ALL SELECT 'tb_municip', COUNT(*) FROM tb_municip
UNION ALL SELECT 'rl', COUNT(*) FROM rl
UNION ALL SELECT 'cadgerrs', COUNT(*) FROM cadgerrs
UNION ALL SELECT 'cbo', COUNT(*) FROM cbo
UNION ALL SELECT 'cid', COUNT(*) FROM cid
UNION ALL SELECT 'procedimentos', COUNT(*) FROM procedimentos;
